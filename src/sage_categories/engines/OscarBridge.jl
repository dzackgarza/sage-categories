"""An affine-scheme morphism from its exact pullback ring map."""
affine_morphism_direct(source_scheme, target_scheme, pullback_map) = morphism(source_scheme, target_scheme, pullback_map)

"""A checked gluing of two affine charts along inverse principal-open maps."""
simple_gluing(left_chart, right_chart, left_to_right, right_to_left) =
    SimpleGluing(left_chart, right_chart, left_to_right, right_to_left)

function affine_open_piecewise_morphism(source_open, target_open, source_patches, target_patches, pullbacks)
    source_patches = collect(source_patches)
    target_patches = collect(target_patches)
    pullbacks = collect(pullbacks)
    length(source_patches) == length(target_patches) == length(pullbacks) ||
        error("piecewise open morphism data have inconsistent lengths")
    target_ambient = ambient_scheme(target_open)
    target_generators = gens(OO(target_ambient))
    maps = AbsAffineSchemeMor[]
    for (source_patch, target_patch, pullback_map) in zip(source_patches, target_patches, pullbacks)
        target_restriction = pullback(inclusion_morphism(target_patch))
        images = [pullback_map(target_restriction(generator)) for generator in target_generators]
        push!(maps, morphism(source_patch, target_ambient, images, check=false))
    end
    AffineSchemeOpenSubschemeMor(source_open, target_open, maps, check=true)
end

function general_gluing(
    left_chart,
    right_chart,
    left_open,
    right_open,
    left_patches,
    right_patches,
    left_to_right_pullbacks,
    right_to_left_pullbacks,
)
    left_to_right = affine_open_piecewise_morphism(
        left_open,
        right_open,
        left_patches,
        right_patches,
        left_to_right_pullbacks,
    )
    right_to_left = affine_open_piecewise_morphism(
        right_open,
        left_open,
        right_patches,
        left_patches,
        right_to_left_pullbacks,
    )
    Gluing(left_chart, right_chart, left_to_right, right_to_left, check=true)
end

function gluing_cocycle(first, second, direct)
    try
        composed = compose(first, second)
        if patches(composed)[1] !== patches(direct)[1]
            direct = inverse(direct)
        end
        composed_map = gluing_morphisms(composed)[1]
        direct_map = gluing_morphisms(direct)[1]
        restricted = restrict(
            direct_map,
            domain(composed_map),
            codomain(composed_map),
            check=true,
        )
        composed_map == restricted
    catch
        false
    end
end

function finite_covered_scheme(patches, gluings)
    covering = Covering(collect(patches))
    for gluing in collect(gluings)
        add_gluing!(covering, gluing)
    end
    CoveredScheme(covering)
end

function covered_open_contains(scheme, smaller, larger)
    try
        restriction_map(StructureSheafOfRings(scheme), larger, smaller)
        true
    catch
        false
    end
end

covered_open_restriction(scheme, larger, smaller) =
    restriction_map(StructureSheafOfRings(scheme), larger, smaller)

function covered_chart_open_preimage(scheme, source_chart, target_open)
    target_chart = ambient_scheme(target_open)
    target_as_open = target_open isa AffineSchemeOpenSubscheme ? target_open : AffineSchemeOpenSubscheme(target_open)
    if source_chart === target_chart
        return target_as_open
    end
    gluing = default_covering(scheme)[source_chart, target_chart]
    forward = gluing_morphisms(gluing)[1]
    target_part = intersect(codomain(forward), target_as_open)
    preimage(forward, target_part)
end

affine_open_complement_equations(open_subset) = collect(complement_equations(open_subset))

function affine_open_equal(first, second)
    affine_open_contains(first, second) && affine_open_contains(second, first)
end


function covered_open_family_compatible(scheme, opens)
    opens = collect(opens)
    cover = default_covering(scheme)
    for left_index in eachindex(opens)
        for right_index in eachindex(opens)
            left_index < right_index || continue
            left_open = opens[left_index]
            right_open = opens[right_index]
            left_chart = ambient_scheme(left_open)
            right_chart = ambient_scheme(right_open)
            gluing = cover[left_chart, right_chart]
            forward = gluing_morphisms(gluing)[1]
            left_part = intersect(left_open, domain(forward))
            right_part = intersect(right_open, codomain(forward))
            transported = preimage(forward, right_part)
            affine_open_equal(left_part, transported) || return false
        end
    end
    true
end


function covered_component_intersection(scheme, source_open, target_open)
    source_chart = ambient_scheme(source_open)
    target_chart = ambient_scheme(target_open)
    source_chart === target_chart && return intersect(source_open, target_open)
    gluing = default_covering(scheme)[source_chart, target_chart]
    forward = gluing_morphisms(gluing)[1]
    target_part = intersect(target_open, codomain(forward))
    intersect(source_open, preimage(forward, target_part))
end


function finite_gluing_mediator(source, target, chart_maps)
    source_cover = default_covering(source)
    target_cover = default_covering(target)
    source_patches = patches(source_cover)
    chart_maps = collect(chart_maps)
    length(source_patches) == length(chart_maps) ||
        error("one chart map is required for each source affine chart")
    local_maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(
        patch => chart_map[patch]
        for (patch, chart_map) in zip(source_patches, chart_maps)
    )
    covering_map = CoveringMorphism(source_cover, target_cover, local_maps; check=false)
    CoveredSchemeMorphism(source, target, covering_map; check=false)
end


"""The covered scheme obtained from two charts and their gluing."""
function glued_covered_scheme(left_chart, right_chart, gluing)
    covering = Covering([left_chart, right_chart])
    add_gluing!(covering, gluing)
    CoveredScheme(covering)
end

covered_patches(scheme) = patches(scheme)

"""The canonical map from one affine chart into a covered scheme containing it."""
function covered_chart_inclusion(source, chart, glued)
    source_cover = default_covering(source)
    target_cover = default_covering(glued)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(chart => identity_map(chart))
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(source, glued, covering_map)
end

"""A covered-scheme map from one affine source chart into a chosen target chart."""
function covered_chart_map(source, source_chart, target, affine_map)
    source_cover = default_covering(source)
    target_cover = default_covering(target)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(source_chart => affine_map)
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(source, target, covering_map)
end

"""The unique covered-scheme map induced by compatible maps on two glued charts."""
function gluing_mediator(glued, target, left_chart, right_chart, left_map, right_map)
    source_cover = default_covering(glued)
    target_cover = default_covering(target)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(
        left_chart => left_map[left_chart],
        right_chart => right_map[right_chart],
    )
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(glued, target, covering_map)
end

