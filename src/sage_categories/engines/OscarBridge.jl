module SageCategoriesOscarBridge

using Oscar

export prime_field, polynomial_ring_with_generators, quotient_ring,
       localization_at_element, localization_at_prime, ring_hom, localization_hom,
       prime_ideal_from_generators, prime_ideal_preimage, ideal_generators, stalk_map,
       map_apply, map_domain, map_codomain, ring_identity, ring_compose, ring_map_equal, ring_generators,
       ring_contains, ring_equal, ring_zero, ring_one, ring_add, ring_multiply, ring_negate,
       ring_coerce, ring_inverse, same_native,
       affine_spec, affine_coordinate_ring, affine_morphism_from_pullback, affine_pullback,
       affine_domain, affine_codomain, covered_scheme_of,
       structure_sheaf, sheaf_value, sheaf_restriction,
       principal_open_subset, principal_open_ambient,
       principal_open_inclusion, affine_morphism_direct,
       simple_gluing, glued_covered_scheme, covered_patches,
       covered_chart_inclusion, gluing_mediator,
       covered_chart_map, covered_domain, covered_codomain,
       covered_identity, covered_compose, covered_equal

"""The prime field ``GF(p)`` used by the affine-ring consumer."""
prime_field(p::Integer) = GF(p)

"""A multivariate polynomial ring over ``base`` with the supplied generator names."""
polynomial_ring_with_generators(base, names) = polynomial_ring(base, Symbol.(collect(names)))

"""The quotient by the ideal generated by ``relations``, together with its projection."""
quotient_ring(ring, relations) = quo(ring, ideal(ring, collect(relations)))

"""The principal localization ``R_f`` and its canonical map ``R -> R_f``."""
localization_at_element(ring, element) = localization(ring, powers_of_element(element))

"""A checked prime ideal generated by ``generators``."""
function prime_ideal_from_generators(ring, generators)
    result = ideal(ring, collect(generators))
    is_prime(result) || error("ideal is not prime")
    result
end

prime_ideal_preimage(map, prime) = preimage(map, prime)
ideal_generators(ideal_value) = collect(gens(ideal_value))

"""The local ring ``R_p`` and its canonical localization map."""
localization_at_prime(ring, prime) = localization(ring, complement_of_prime_ideal(prime))

"""The induced local map ``A_p -> B_q`` for ``p = phi^-1(q)``."""
function stalk_map(phi, source_localized, target_localized, target_localization)
    restricted = compose(phi, target_localization)
    hom(source_localized, target_localized, restricted)
end

"""The ring homomorphism determined by the images of the source generators."""
ring_hom(source, target, images) = hom(source, target, collect(images))

"""Extend a ring map across a principal localization when the selected element becomes a unit."""
localization_hom(localized, target, base_map) = hom(localized, target, base_map)

map_apply(map, element) = map(element)
map_domain(map) = domain(map)
map_codomain(map) = codomain(map)
ring_identity(ring) = identity_map(ring)
ring_compose(second, first) = compose(first, second)
ring_map_equal(first, second) = first == second
ring_generators(ring) = gens(ring)
ring_contains(ring, element) = try
    parent(element) === ring
catch
    false
end
ring_equal(first, second) = first == second
ring_zero(ring) = zero(ring)
ring_one(ring) = one(ring)
ring_add(first, second) = first + second
ring_multiply(first, second) = first * second
ring_negate(element) = -element
ring_coerce(ring, value) = ring(value)
ring_inverse(element) = inv(element)
same_native(first, second) = first === second

"""The affine scheme ``Spec(R)`` for a supported OSCAR coordinate ring."""
affine_spec(ring) = spec(ring)
affine_coordinate_ring(scheme) = OO(scheme)

"""The affine morphism ``Spec(B) -> Spec(A)`` defined by a ring map ``A -> B``."""
function affine_morphism_from_pullback(source_scheme, target_scheme, ring_map)
    images = [ring_map(generator) for generator in gens(OO(target_scheme))]
    morphism(source_scheme, target_scheme, images)
end

affine_pullback(map) = pullback(map)
affine_domain(map) = domain(map)
affine_codomain(map) = codomain(map)
covered_scheme_of(scheme) = covered_scheme(scheme)
structure_sheaf(scheme) = StructureSheafOfRings(scheme)
sheaf_value(sheaf, open_subset) = sheaf(open_subset)
sheaf_restriction(sheaf, larger, smaller) = restriction_map(sheaf, larger, smaller)
principal_open_subset(scheme, element) = PrincipalOpenSubset(scheme, element)
principal_open_ambient(open_subset) = ambient_scheme(open_subset)
principal_open_inclusion(open_subset) = inclusion_morphism(open_subset)

"""An affine-scheme morphism from its exact pullback ring map."""
affine_morphism_direct(source_scheme, target_scheme, pullback_map) = morphism(source_scheme, target_scheme, pullback_map)

"""A checked gluing of two affine charts along inverse principal-open maps."""
simple_gluing(left_chart, right_chart, left_to_right, right_to_left) =
    SimpleGluing(left_chart, right_chart, left_to_right, right_to_left)

"""The covered scheme obtained from two charts and their gluing."""
function glued_covered_scheme(left_chart, right_chart, gluing)
    covering = Covering([left_chart, right_chart])
    add_gluing!(covering, gluing)
    CoveredScheme(covering)
end

covered_patches(scheme) = patches(scheme)

"""The canonical map from one affine chart into a covered scheme containing it."""
function covered_chart_inclusion(source, chart, glued)
    source_cover = default_covering(source)
    target_cover = default_covering(glued)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(chart => identity_map(chart))
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(source, glued, covering_map)
end

"""A covered-scheme map from one affine source chart into a chosen target chart."""
function covered_chart_map(source, source_chart, target, affine_map)
    source_cover = default_covering(source)
    target_cover = default_covering(target)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(source_chart => affine_map)
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(source, target, covering_map)
end

"""The unique covered-scheme map induced by compatible maps on two glued charts."""
function gluing_mediator(glued, target, left_chart, right_chart, left_map, right_map)
    source_cover = default_covering(glued)
    target_cover = default_covering(target)
    maps = IdDict{AbsAffineScheme, AbsAffineSchemeMor}(
        left_chart => left_map[left_chart],
        right_chart => right_map[right_chart],
    )
    covering_map = CoveringMorphism(source_cover, target_cover, maps)
    CoveredSchemeMorphism(glued, target, covering_map)
end

covered_domain(map) = domain(map)
covered_codomain(map) = codomain(map)
covered_identity(scheme) = identity_map(scheme)
covered_compose(second, first) = compose(first, second)
covered_equal(first, second) = first == second

end
