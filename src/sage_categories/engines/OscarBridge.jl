"""The prime field ``GF(p)`` used by the affine-ring consumer."""
prime_field(p::Integer) = GF(p)

"""A multivariate polynomial ring over ``base`` with the supplied generator names."""
polynomial_ring_with_generators(base, names) = polynomial_ring(base, Symbol.(collect(names)))

"""The quotient by the ideal generated by ``relations``, together with its projection."""
quotient_ring(ring, relations) = quo(ring, ideal(ring, collect(relations)))

"""The principal localization ``R_f`` and its canonical map ``R -> R_f``."""
localization_at_element(ring, element) = localization(ring, powers_of_element(element))

"""A checked prime ideal generated by ``generators``."""
function prime_ideal_from_generators(ring, generators)
    result = ideal(ring, collect(generators))
    is_prime(result) || error("ideal is not prime")
    result
end

prime_ideal_preimage(map, prime) = preimage(map, prime)

function prime_ideal_extension(map, prime)
    target = codomain(map)
    images = [map(generator) for generator in gens(prime)]
    result = isempty(images) ? ideal(target, zero(target)) : ideal(target, images)
    is_prime(result) || error("extended ideal is not prime")
    result
end

ideal_generators(ideal_value) = collect(gens(ideal_value))
ideal_contains(ideal_value, element) = element in ideal_value

"""The local ring ``R_p`` and its canonical localization map."""
localization_at_prime(ring, prime) = localization(ring, complement_of_prime_ideal(prime))

"""The induced local map ``A_p -> B_q`` for ``p = phi^-1(q)``."""
function stalk_map(phi, source_localized, target_localized, target_localization)
    restricted = compose(phi, target_localization)
    hom(source_localized, target_localized, restricted)
end

"""The ring homomorphism determined by the images of the source generators."""
ring_hom(source, target, images) = hom(source, target, collect(images))

"""Extend a ring map across a principal localization when the selected element becomes a unit."""
localization_hom(localized, target, base_map) = hom(localized, target, base_map)

map_apply(map, element) = map(element)
