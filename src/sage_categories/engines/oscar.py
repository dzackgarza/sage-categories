def version() -> str:
    """Return the OSCAR package version loaded by the isolated worker."""
    return bridge().text("version")


def prime_field(characteristic: int) -> OscarHandle:
    """Return OSCAR's prime field ``GF(characteristic)``."""
    return bridge().handle("prime_field", characteristic)


def polynomial_ring(base: OscarHandle, names: tuple[str, ...]) -> tuple[OscarHandle, tuple[OscarHandle, ...]]:
    """Return OSCAR's multivariate polynomial ring and its ordered generators."""
    ring, generators = bridge().handle_and_handles("polynomial_ring_with_generators", base, list(names))
    return ring, tuple(generators)


def quotient(ring: OscarHandle, relations: tuple[OscarHandle, ...]) -> tuple[OscarHandle, OscarHandle]:
    """Return ``ring/(relations)`` and its canonical projection."""
    quotient_ring, projection = bridge().pair("quotient_ring", ring, list(relations))
    return quotient_ring, projection


def localization_at_element(ring: OscarHandle, element: OscarHandle) -> tuple[OscarHandle, OscarHandle]:
    """Return the principal localization ``ring[element^-1]`` and its canonical map."""
    localized, canonical = bridge().pair("localization_at_element", ring, element)
    return localized, canonical


def prime_ideal(ring: OscarHandle, generators: tuple[OscarHandle, ...]) -> OscarHandle:
    """Return the checked OSCAR prime ideal generated by ``generators``."""
    return bridge().handle("prime_ideal_from_generators", ring, list(generators))


def prime_ideal_preimage(mapping: OscarHandle, prime: OscarHandle) -> OscarHandle:
    """Return the inverse-image prime ideal under ``mapping``."""
    return bridge().handle("prime_ideal_preimage", mapping, prime)


def localization_at_prime(ring: OscarHandle, prime: OscarHandle) -> tuple[OscarHandle, OscarHandle]:
    """Return the local ring ``ring_prime`` and its canonical map."""
    localized, canonical = bridge().pair("localization_at_prime", ring, prime)
    return localized, canonical


